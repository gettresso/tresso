// Writes (or, with --check, compares) apps/whatsapp-bridge/THIRD-PARTY-NOTICES.txt: every Go module linked into the
// WhatsApp bridge binary, as `go version -m` lists it, with the license texts of that module version from the Go
// module cache. Tresso for Mac ships the file next to the bridge (tauri.macos.conf.json, bundle > resources).
//
//   node apps/desktop/scripts/whatsapp-bridge-notices.mjs --write <bridge binary>
//   node apps/desktop/scripts/whatsapp-bridge-notices.mjs --check <bridge binary>
//
// The binary is one `go build` made from apps/whatsapp-bridge (build-whatsapp-bridge.mjs builds one and runs --check
// with it). The module cache is filled first (`go mod download`), so the texts are those of the pinned versions.
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [mode, binary] = process.argv.slice(2)
if (!['--write', '--check'].includes(mode) || binary === undefined) {
  console.error('Usage: whatsapp-bridge-notices.mjs --write|--check <bridge binary>')
  process.exit(64)
}

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '..', '..', 'whatsapp-bridge')
const target = join(source, 'THIRD-PARTY-NOTICES.txt')

function go(args) {
  return execFileSync('go', args, { cwd: source, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] })
}

/** The modules the binary links, from its build info: `dep` lines, with a replacement (`=>`) where there is one. */
function modules(info) {
  const found = []
  for (const line of info.split('\n')) {
    const fields = line.trim().split(/\s+/)
    if (fields[0] === 'dep') {
      found.push({ path: fields[1], version: fields[2], source: { path: fields[1], version: fields[2] } })
    } else if (fields[0] === '=>' && found.length > 0) {
      found[found.length - 1].source = { path: fields[1], version: fields[2] }
    }
  }
  return found.sort((a, b) => a.path.localeCompare(b.path))
}

/** A module path as the module cache spells it: an upper-case letter is `!` and the letter in lower case. */
function cachePath(path) {
  return path.replace(/[A-Z]/g, (letter) => `!${letter.toLowerCase()}`)
}

/** The license files at the top of a module: LICENSE, LICENCE, COPYING, NOTICE and PATENTS, with any suffix. */
function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((name) => /^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([.\-_].*)?$/i.test(name))
    .sort()
}

const info = go(['version', '-m', binary])
go(['mod', 'download'])
const cache = go(['env', 'GOMODCACHE']).trim()
const rule = '='.repeat(118)

const parts = [
  `Third-party notices for the WhatsApp bridge in Tresso for Mac (Tresso.app/Contents/MacOS/whatsapp-bridge)

This file ships as Tresso.app/Contents/Resources/licenses/whatsapp-bridge-third-party-notices.txt.

The bridge is built from apps/whatsapp-bridge in Tresso's public repository, https://github.com/gettresso/tresso, at
the tag of the release this app was built from. Its go.mod and go.sum there pin the exact version of every module
below. Tresso, the bridge included, is licensed under the GNU Affero General Public License version 3 (AGPL-3.0-only).

The bridge links go.mau.fi/libsignal, licensed under the GNU General Public License version 3 (GPL-3.0), and
go.mau.fi/whatsmeow and go.mau.fi/util, licensed under the Mozilla Public License 2.0 (MPL-2.0), together with modules
under the BSD-3-Clause, MIT, ISC and Apache-2.0 licenses. The complete source code of the bridge and of each of these
modules, at the versions named, is available from the repository above (with go.mod and go.sum) and from each
module's own repository; \`go mod download\` in apps/whatsapp-bridge fetches every one of them.

Part of the bridge comes from lharries/whatsapp-mcp, licensed under the MIT license; its notice follows first, then
every module the binary links with its license texts.

This file is generated by apps/desktop/scripts/whatsapp-bridge-notices.mjs from \`go version -m\` and the Go module
cache; do not edit it by hand.`,
  `${rule}\ntresso/whatsapp-bridge (apps/whatsapp-bridge/NOTICE)\n${rule}\n\n${readFileSync(join(source, 'NOTICE'), 'utf8').trim()}`,
]

const missing = []
for (const module of modules(info)) {
  const dir = join(cache, `${cachePath(module.source.path)}@${module.source.version}`)
  let files = []
  try {
    files = licenseFiles(dir)
  } catch {
    // Not in the cache: reported below.
  }
  if (files.length === 0) {
    missing.push(`${module.path} ${module.version}`)
    continue
  }
  const replaced = module.source.path === module.path && module.source.version === module.version ? '' : ` (replaced by ${module.source.path} ${module.source.version})`
  const texts = files.map((name) => `--- ${name}\n\n${readFileSync(join(dir, name), 'utf8').trim()}`)
  parts.push(`${rule}\n${module.path} ${module.version}${replaced}\n${rule}\n\n${texts.join('\n\n')}`)
}
if (missing.length > 0) {
  console.error(`No license file found for: ${missing.join(', ')}`)
  process.exit(1)
}

const text = `${parts.join('\n\n')}\n`
if (mode === '--write') {
  writeFileSync(target, text)
  console.log(`Wrote ${target}`)
} else {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // Compared as empty below.
  }
  if (current !== text) {
    console.error(`${target} does not match the bridge's modules. Write it again: node apps/desktop/scripts/whatsapp-bridge-notices.mjs --write <bridge binary>`)
    process.exit(1)
  }
}
